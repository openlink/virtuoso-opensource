#!/usr/bin/env python3
#
#  gen_bpe_classes.py
#
#  Writes onnx_bpe_classes.h: the character classes the byte-level BPE
#  pre-tokenizer needs, read from the Hugging Face tokenizer itself.
#
#  RoBERTa's (and GPT-2's) pre-tokenizer splits text with
#      's|'t|'re|'ve|'m|'ll|'d| ?\p{L}+| ?\p{N}+| ?[^\s\p{L}\p{N}]+|\s+(?!\S)|\s+
#  so every character is a letter, a number, a space or something else.  Which
#  class a character falls in depends on the regex engine's Unicode tables, so
#  rather than trust a Unicode version to agree with it, this asks the engine:
#  a character is a letter if "a" + c pre-tokenizes to one piece, a number if
#  "1" + c does, "other" if "!" + c does, and a space otherwise.
#
#  The strip table is Python's str.isspace, which sentence-transformers uses to
#  strip every text before tokenizing it.
#
#      python3 gen_bpe_classes.py [model] > onnx_bpe_classes.h
#
#  Needs transformers (and its tokenizers); the default model is the bundled
#  granite-embedding-30m-english, whose tokenizer is RoBERTa's.

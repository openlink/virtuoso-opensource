import sys

from transformers import AutoTokenizer

MODEL = sys.argv[1] if len(sys.argv) > 1 else "ibm-granite/granite-embedding-30m-english"
MAX_CP = 0x110000


def main():
    pre = AutoTokenizer.from_pretrained(MODEL).backend_tokenizer.pre_tokenizer.pre_tokenize_str
    cls = bytearray(MAX_CP)             # 0 other, 1 letter, 2 number, 3 space
    for c in range(MAX_CP):
        if 0xD800 <= c <= 0xDFFF:
            continue                    # surrogates: not characters
        s = chr(c)
        if len(pre("a" + s)) == 1:
            cls[c] = 1
        elif len(pre("1" + s)) == 1:
            cls[c] = 2
        elif len(pre("!" + s)) == 1:
            cls[c] = 0
        else:
            cls[c] = 3

    def ranges(pred):
        out, start = [], None
        for c in range(MAX_CP + 1):
            hit = c < MAX_CP and not (0xD800 <= c <= 0xDFFF) and pred(c)
            if hit and start is None:
                start = c
            elif not hit and start is not None:
                out.append((start, c - 1))
                start = None
        return out

    tables = [
        ("bpe_letter_ranges", "letters: \\p{L} as the pre-tokenizer sees it",
         ranges(lambda c: cls[c] == 1)),
        ("bpe_number_ranges", "numbers: \\p{N}", ranges(lambda c: cls[c] == 2)),
        ("bpe_space_ranges", "spaces: \\s", ranges(lambda c: cls[c] == 3)),
        ("bpe_strip_ranges", "Python's str.isspace: what sentence-transformers strips",
         ranges(lambda c: chr(c).isspace())),
    ]

    w = sys.stdout.write
    w("/* onnx_bpe_classes.h -- generated by gen_bpe_classes.py from the %s\n" % MODEL)
    w("   tokenizer's own pre-tokenizer.  Do not edit; regenerate. */\n\n")
    for name, what, rs in tables:
        w("/* %s: %d ranges */\n" % (what, len(rs)))
        w("static const uint32_t %s[][2] = {\n" % name)
        for i in range(0, len(rs), 4):
            w("  " + ", ".join("{ 0x%04X, 0x%04X }" % r for r in rs[i:i + 4]) + ",\n")
        w("};\n\n")


if __name__ == "__main__":
    main()
